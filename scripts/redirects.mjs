// Generates public/_redirects from the old newsroom sitemap. Run once: node scripts/redirects.mjs [--from <file>] [--dry-run]
import { readFile, writeFile } from 'node:fs/promises';

const args = process.argv.slice(2);
const from = args.includes('--from') ? args[args.indexOf('--from') + 1] : null;
const dry = args.includes('--dry-run');
const INDEX = 'https://poludzku.info/sitemap-index.xml';
const FIXED = ['/kalendarz', '/zapisane', '/metoda', '/rss.xml', '/kalendarz.ics', '/llms.txt'];
const SERVED = /^\/(regulamin|newsroom|wyloguj|(en|gh|zaloguj|avatar)(\/|$))/;

const locs = (xml) => [...xml.matchAll(/<loc>\s*([^<\s]+)\s*<\/loc>/g)].map((m) => m[1]);
const get = async (url) => {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.text();
};

try {
  const urls = from
    ? locs(await readFile(from, 'utf8'))
    : (await Promise.all(locs(await get(INDEX)).map(async (u) => locs(await get(u))))).flat();
  if (!urls.length) throw new Error('no <loc> entries found');
  const paths = new Set(FIXED);
  for (const u of urls) {
    const p = new URL(u).pathname.replace(/\/$/, '');
    if (/^\/[^/]+(\/[^/]+)?$/.test(p) && !SERVED.test(p)) paths.add(p);
  }
  const lines = [...paths].sort().map((p) => `${p} /newsroom 301`);
  console.log(`${lines.length} redirect rules`);
  if (!dry) await writeFile('public/_redirects', `# Generated by scripts/redirects.mjs from the old newsroom sitemap\n${lines.join('\n')}\n`);
} catch (e) {
  console.error(e.message);
  process.exit(1);
}
